#!/usr/bin/env node
// Composes the full GitHub Pages site into an output directory:
//   <out>/                     copy of the trunk branch (the live site)
//   <out>/previews/<branch>/   copy of every other branch
//   <out>/previews/index.html  generated index of all branch previews
//
// Read-only with respect to the repo: it only writes to the output directory.
// Run by .github/workflows/deploy-pages.yml on every push; the workflow then
// force-pushes the result to the gh-pages branch, which GitHub Pages serves.
//
// Local dry run:
//   git fetch origin && node scripts/build-preview-site.mjs /tmp/site
//
// Usage: build-preview-site.mjs [out-dir]
//   out-dir       output directory (default: _site; wiped first)
//   ROOT_BRANCH   env var naming the branch served at the root; the workflow
//                 passes the repo's default branch, a local dry run falls
//                 back to origin/HEAD

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const OUT = path.resolve(process.argv[2] || "_site");

const git = (...args) =>
  execFileSync("git", args, { encoding: "utf8", maxBuffer: 1 << 28, stdio: ["pipe", "pipe", "pipe"] });

function detectTrunk() {
  try {
    return git("symbolic-ref", "--short", "refs/remotes/origin/HEAD")
      .trim().replace(/^origin\//, "");
  } catch {
    return "main";
  }
}

const ROOT_BRANCH = process.env.ROOT_BRANCH || detectTrunk();
// gh-pages is our own output; HEAD is the symref actions/checkout leaves behind.
const SKIP = new Set([ROOT_BRANCH, "gh-pages", "HEAD"]);

// Extract a branch's tree into dest without a checkout. No shell involved, so
// branch names never touch shell quoting.
function extract(ref, dest) {
  fs.mkdirSync(dest, { recursive: true });
  const tarball = execFileSync("git", ["archive", ref], { maxBuffer: 1 << 28 });
  execFileSync("tar", ["-x", "-C", dest], { input: tarball });
  // The workflow directory only matters to Actions, not to the served site.
  fs.rmSync(path.join(dest, ".github"), { recursive: true, force: true });
}

function branchInfo(name) {
  const [sha, date, subject] = git(
    "log", "-1", "--format=%H%x00%cI%x00%s", `origin/${name}`
  ).trim().split("\0");
  return { name, sha, date, subject };
}

const esc = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// Branch names may contain slashes; encode each path segment for hrefs.
const branchHref = (name) =>
  name.split("/").map(encodeURIComponent).join("/") + "/";

function indexHtml(branches, mainSha) {
  const rows = branches.map((b) => `
      <li class="preview">
        <a class="branch" href="${branchHref(b.name)}">${esc(b.name)}</a>
        <span class="meta">${esc(b.sha.slice(0, 7))} &middot; ${esc(b.date.slice(0, 10))}</span>
        <div class="subject">${esc(b.subject)}</div>
      </li>`).join("\n");
  const empty = `<p class="subject">No branches besides ${esc(ROOT_BRANCH)} right now. Push one and it will appear here.</p>`;
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta name="robots" content="noindex" />
<title>Branch previews &middot; Inn Menu Simulator</title>
<style>
:root { --desk: #cfc2a5; --page: #f5eedb; --ink: #2c2216; --ink-soft: #5c5140; --rule: #d8cba9; --rubric: #9e2b25; }
@media (prefers-color-scheme: dark) {
  :root { --desk: #12100b; --page: #241f14; --ink: #e9dcc0; --ink-soft: #b3a68a; --rule: #453c28; --rubric: #d96f52; }
}
* { box-sizing: border-box; }
body { margin: 0; background: var(--desk); color: var(--ink); font-family: Georgia, serif; font-size: 17px; line-height: 1.5; }
.sheet { max-width: 620px; margin: 3rem auto 4rem; padding: 2.5rem 2.75rem; background: var(--page); border: 1px solid var(--rule); border-radius: 4px; }
h1 { font-weight: 400; font-size: 1.6rem; margin: 0 0 0.15rem; }
.tagline { font-style: italic; font-size: 0.9rem; color: var(--rubric); margin: 0 0 1.5rem; }
a { color: var(--rubric); }
ul { list-style: none; padding: 0; margin: 0; }
.preview { padding: 0.7rem 0; border-bottom: 1px solid var(--rule); }
.branch { font-size: 1.05rem; }
.meta { font-size: 0.8rem; color: var(--ink-soft); margin-left: 0.5rem; }
.subject { font-size: 0.9rem; font-style: italic; color: var(--ink-soft); }
.foot { margin-top: 1.5rem; font-size: 0.8rem; font-style: italic; color: var(--ink-soft); }
</style>
</head>
<body>
<main class="sheet">
  <h1>Branch previews</h1>
  <p class="tagline">every branch of the inn, bound and shelved</p>
  <ul>${rows || ""}</ul>
  ${branches.length ? "" : empty}
  <p class="foot">
    Live site (<code>${esc(ROOT_BRANCH)}</code> @ ${esc(mainSha.slice(0, 7))}): <a href="../">go to the root</a>.<br />
    Generated by <code>deploy-pages.yml</code> on every push; deleted branches drop off automatically.
  </p>
</main>
</body>
</html>
`;
}

fs.rmSync(OUT, { recursive: true, force: true });

extract(`origin/${ROOT_BRANCH}`, OUT);
// Pages runs the site through Jekyll unless told not to.
fs.writeFileSync(path.join(OUT, ".nojekyll"), "");

const branches = git("for-each-ref", "--format=%(refname:short)", "refs/remotes/origin")
  .trim().split("\n").filter(Boolean)
  .map((r) => r.replace(/^origin\//, ""))
  .filter((b) => !SKIP.has(b))
  .map(branchInfo)
  .sort((a, b) => b.date.localeCompare(a.date));

for (const b of branches) {
  extract(`origin/${b.name}`, path.join(OUT, "previews", b.name));
}

const mainSha = git("rev-parse", `origin/${ROOT_BRANCH}`).trim();
fs.mkdirSync(path.join(OUT, "previews"), { recursive: true });
fs.writeFileSync(path.join(OUT, "previews", "index.html"), indexHtml(branches, mainSha));

console.log(`Composed site at ${OUT}`);
console.log(`  root: ${ROOT_BRANCH} @ ${mainSha.slice(0, 7)}`);
for (const b of branches) console.log(`  previews/${b.name}: ${b.sha.slice(0, 7)} (${b.date})`);
